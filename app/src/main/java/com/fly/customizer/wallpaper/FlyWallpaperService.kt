package com.fly.customizer.wallpaper

import android.graphics.Bitmap
import android.graphics.Canvas
import android.graphics.Paint
import android.graphics.Rect
import android.os.Handler
import android.os.Looper
import android.os.SystemClock
import android.service.wallpaper.WallpaperService
import android.util.Log
import android.view.SurfaceHolder
import com.fly.customizer.FlyApp
import com.fly.customizer.R
import com.fly.customizer.core.Prefs
import com.fly.customizer.util.AnimatedWallpaper
import com.fly.customizer.util.AnimatedWallpaperCatalog
import com.fly.customizer.util.NativeFly

/**
 * Real Android live wallpaper: every visible frame is generated by libflycore.so and blitted to
 * the wallpaper surface. Rendering stops as soon as the engine is hidden, and the frame buffer is
 * rendered at a reduced resolution to keep the cost of a full-screen animation reasonable.
 */
class FlyWallpaperService : WallpaperService() {

    override fun onCreateEngine(): Engine = FlyEngine()

    private inner class FlyEngine : Engine() {

        private val handler = Handler(Looper.getMainLooper())
        private val paint = Paint(Paint.FILTER_BITMAP_FLAG or Paint.DITHER_FLAG)
        private val destination = Rect()

        private var preset: AnimatedWallpaper = AnimatedWallpaperCatalog.presets.first()
        private var pixels: IntArray? = null
        private var frame: Bitmap? = null
        private var frameWidth = 0
        private var frameHeight = 0
        private var surfaceWidth = 0
        private var surfaceHeight = 0
        private var phase = 0f
        private var lastStepAt = 0L
        private var visible = false
        private var reduceMotion = false
        private var frameDelay = 33L
        private var scrollFactor = 1f
        private var recordedRun = false

        private val tick = object : Runnable {
            override fun run() {
                if (!visible) return
                step()
                if (!reduceMotion) {
                    handler.postDelayed(this, frameDelay)
                }
            }
        }

        override fun onCreate(surfaceHolder: SurfaceHolder) {
            super.onCreate(surfaceHolder)
            setOffsetNotificationsEnabled(true)
            loadPreferences()
        }

        override fun onSurfaceChanged(holder: SurfaceHolder, format: Int, width: Int, height: Int) {
            super.onSurfaceChanged(holder, format, width, height)
            surfaceWidth = width.coerceAtLeast(1)
            surfaceHeight = height.coerceAtLeast(1)
            releaseBuffers()
            allocateBuffers()
            step()
        }

        override fun onSurfaceDestroyed(holder: SurfaceHolder) {
            visible = false
            handler.removeCallbacks(tick)
            releaseBuffers()
            super.onSurfaceDestroyed(holder)
        }

        override fun onVisibilityChanged(visible: Boolean) {
            this.visible = visible
            handler.removeCallbacks(tick)
            if (!visible) return
            loadPreferences()
            lastStepAt = SystemClock.elapsedRealtime()
            tick.run()
            rememberRunning()
        }

        override fun onOffsetsChanged(
            xOffset: Float,
            yOffset: Float,
            xOffsetStep: Float,
            yOffsetStep: Float,
            xPixelOffset: Int,
            yPixelOffset: Int,
        ) {
            // Scrolling the home screen gently speeds up or slows the animation.
            scrollFactor = 0.75f + xOffset * 0.5f
        }

        override fun onSurfaceRedrawNeeded(holder: SurfaceHolder) {
            super.onSurfaceRedrawNeeded(holder)
            val bitmap = frame ?: return
            draw(bitmap)
        }

        private fun loadPreferences() {
            val prefs = Prefs(applicationContext)
            preset = AnimatedWallpaperCatalog.presetOrDefault(prefs.liveWallpaperId)
            reduceMotion = prefs.reduceMotion
            frameDelay = (1000L / prefs.liveFps.coerceIn(Prefs.MIN_FPS, Prefs.MAX_FPS))
                .coerceAtLeast(16L)
        }

        private fun allocateBuffers() {
            if (surfaceWidth <= 1 || surfaceHeight <= 1) return
            val quality = Prefs(applicationContext).wallpaperQuality
            val divisor = when (quality) {
                Prefs.QUALITY_SMALL -> 3
                Prefs.QUALITY_FULL -> 1
                else -> 2
            }
            frameWidth = (surfaceWidth / divisor).coerceIn(180, 1440)
            frameHeight = (surfaceHeight / divisor).coerceIn(180, 2560)
            try {
                pixels = IntArray(frameWidth * frameHeight)
                frame = Bitmap.createBitmap(frameWidth, frameHeight, Bitmap.Config.ARGB_8888)
            } catch (error: OutOfMemoryError) {
                Log.e(TAG, "Unable to allocate ${frameWidth}x$frameHeight frame buffer", error)
                releaseBuffers()
            }
        }

        private fun releaseBuffers() {
            frame?.recycle()
            frame = null
            pixels = null
        }

        private fun step() {
            val bitmap = frame ?: return
            val buffer = pixels ?: return
            val now = SystemClock.elapsedRealtime()
            if (!reduceMotion) {
                val delta = (now - lastStepAt).coerceIn(0L, 250L)
                lastStepAt = now
                phase += delta / 1000f * preset.speed * scrollFactor
                if (phase > 720f) phase -= 720f
            }
            try {
                AnimatedWallpaperCatalog.renderFrame(
                    preset, buffer, frameWidth, frameHeight, phase,
                )
                bitmap.setPixels(buffer, 0, frameWidth, 0, 0, frameWidth, frameHeight)
            } catch (error: Throwable) {
                Log.e(TAG, "Frame generation failed", error)
                return
            }
            draw(bitmap)
        }

        private fun draw(bitmap: Bitmap) {
            if (bitmap.isRecycled || surfaceWidth <= 1) return
            val holder = surfaceHolder ?: return
            val canvas: Canvas = try {
                holder.lockCanvas()
            } catch (error: Exception) {
                Log.w(TAG, "Wallpaper surface is not ready", error)
                return
            } ?: return
            try {
                destination.set(0, 0, surfaceWidth, surfaceHeight)
                canvas.drawBitmap(bitmap, null, destination, paint)
            } finally {
                try {
                    holder.unlockCanvasAndPost(canvas)
                } catch (error: Exception) {
                    Log.w(TAG, "Unable to post wallpaper frame", error)
                }
            }
        }

        /**
         * The engine only becomes visible once the launcher is actually showing the wallpaper, so
         * this is the moment a live wallpaper is genuinely in use.
         */
        private fun rememberRunning() {
            if (recordedRun) return
            recordedRun = true
            val app = applicationContext as? FlyApp ?: return
            val label = try {
                app.getString(preset.labelRes)
            } catch (error: Exception) {
                preset.id
            }
            val target = try {
                app.getString(R.string.target_live)
            } catch (error: Exception) {
                "Live wallpaper"
            }
            val presetId = preset.id
            Thread {
                try {
                    FlyApp.repository.recordApply("live:$presetId", label, target)
                } catch (error: Exception) {
                    Log.w(TAG, "Unable to record the live wallpaper", error)
                }
            }.start()
        }
    }

    private companion object {
        const val TAG = "FlyWallpaper"
    }
}
